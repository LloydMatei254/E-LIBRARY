create or replace function public.get_schema_summary()
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_table record;
  v_columns jsonb;
  v_foreign_keys jsonb;
  v_record_count bigint;
  v_tables jsonb := '[]'::jsonb;
begin
  if not public.is_library_staff() then
    raise exception 'Only library staff can view schema details.' using errcode = '42501';
  end if;

  for v_table in
    select table_name
    from information_schema.tables
    where table_schema = 'public' and table_type = 'BASE TABLE'
    order by table_name
  loop
    select coalesce(jsonb_agg(jsonb_build_object(
      'cid', c.ordinal_position - 1,
      'name', c.column_name,
      'type', c.data_type,
      'notnull', case when c.is_nullable = 'NO' then 1 else 0 end,
      'pk', case when exists (
        select 1
        from information_schema.table_constraints tc
        join information_schema.key_column_usage kcu
          on kcu.constraint_name = tc.constraint_name and kcu.constraint_schema = tc.constraint_schema
        where tc.constraint_type = 'PRIMARY KEY'
          and tc.table_schema = c.table_schema
          and tc.table_name = c.table_name
          and kcu.column_name = c.column_name
      ) then 1 else 0 end
    ) order by c.ordinal_position), '[]'::jsonb)
    into v_columns
    from information_schema.columns c
    where c.table_schema = 'public' and c.table_name = v_table.table_name;

    select coalesce(jsonb_agg(jsonb_build_object(
      'table', ccu.table_name,
      'from', kcu.column_name,
      'to', ccu.column_name
    )), '[]'::jsonb)
    into v_foreign_keys
    from information_schema.table_constraints tc
    join information_schema.key_column_usage kcu
      on kcu.constraint_name = tc.constraint_name and kcu.constraint_schema = tc.constraint_schema
    join information_schema.constraint_column_usage ccu
      on ccu.constraint_name = tc.constraint_name and ccu.constraint_schema = tc.constraint_schema
    where tc.constraint_type = 'FOREIGN KEY'
      and tc.table_schema = 'public'
      and tc.table_name = v_table.table_name;

    execute format('select count(*) from public.%I', v_table.table_name) into v_record_count;
    v_tables := v_tables || jsonb_build_array(jsonb_build_object(
      'table_name', v_table.table_name,
      'record_count', v_record_count,
      'columns', v_columns,
      'foreign_keys', v_foreign_keys
    ));
  end loop;

  return jsonb_build_object(
    'db_type', 'Supabase PostgreSQL',
    'tables_count', jsonb_array_length(v_tables),
    'tables', v_tables
  );
end;
$$;

create or replace function public.can_upload_book_cover(p_object_name text)
returns boolean
language plpgsql
security definer
set search_path = public, storage, pg_temp
as $$
declare
  v_category_id bigint;
  v_image_count bigint;
begin
  if not public.is_library_staff()
    or p_object_name !~ '^categories/[0-9]+/[A-Za-z0-9_-]+\.(jpg|jpeg|png|webp)$' then
    return false;
  end if;

  v_category_id := split_part(p_object_name, '/', 2)::bigint;
  if not exists (select 1 from public.categories where category_id = v_category_id) then
    return false;
  end if;

  perform pg_advisory_xact_lock(hashtextextended('book-covers:' || v_category_id::text, 0));

  select count(*)
  into v_image_count
  from storage.objects
  where bucket_id = 'book-covers'
    and name like format('categories/%s/%%', v_category_id);

  return v_image_count < 50;
end;
$$;

