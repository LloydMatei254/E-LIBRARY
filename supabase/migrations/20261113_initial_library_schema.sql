create or replace function public.save_book(p_book_id bigint, p_payload jsonb)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_book_id bigint;
  v_old_total integer;
  v_old_available integer;
  v_total integer;
  v_available integer;
  v_author_name text;
  v_author_id bigint;
begin
  if not public.is_library_staff() then
    raise exception 'Only library staff can manage books.' using errcode = '42501';
  end if;

  v_total := greatest(0, coalesce((p_payload ->> 'total_copies')::integer, 1));

  if p_book_id is null then
    insert into public.books (
      isbn, title, category_id, publisher, publication_year, language, pages,
      total_copies, available_copies, shelf_location, description, cover_image, added_by
    )
    values (
      btrim(coalesce(p_payload ->> 'isbn', '')),
      btrim(coalesce(p_payload ->> 'title', '')),
      (p_payload ->> 'category_id')::bigint,
      coalesce(p_payload ->> 'publisher', ''),
      nullif(p_payload ->> 'publication_year', '')::integer,
      coalesce(p_payload ->> 'language', 'English'),
      nullif(p_payload ->> 'pages', '')::integer,
      v_total,
      v_total,
      coalesce(p_payload ->> 'shelf_location', ''),
      coalesce(p_payload ->> 'description', ''),
      coalesce(p_payload ->> 'cover_image', ''),
      public.current_member_id()
    )
    returning book_id into v_book_id;
  else
    select b.total_copies, b.available_copies
    into v_old_total, v_old_available
    from public.books b
    where b.book_id = p_book_id
    for update;

    if not found then
      raise exception 'Book not found.';
    end if;

    v_available := greatest(0, least(v_total, v_old_available + v_total - v_old_total));

    update public.books
    set isbn = btrim(coalesce(p_payload ->> 'isbn', isbn)),
        title = btrim(coalesce(p_payload ->> 'title', title)),
        category_id = coalesce((p_payload ->> 'category_id')::bigint, category_id),
        publisher = coalesce(p_payload ->> 'publisher', ''),
        publication_year = nullif(p_payload ->> 'publication_year', '')::integer,
        language = coalesce(p_payload ->> 'language', 'English'),
        pages = nullif(p_payload ->> 'pages', '')::integer,
        total_copies = v_total,
        available_copies = v_available,
        shelf_location = coalesce(p_payload ->> 'shelf_location', ''),
        description = coalesce(p_payload ->> 'description', ''),
        cover_image = coalesce(p_payload ->> 'cover_image', '')
    where book_id = p_book_id
    returning book_id into v_book_id;

    delete from public.book_authors where book_id = v_book_id;
  end if;

  for v_author_name in
    select distinct btrim(value)
    from jsonb_array_elements_text(coalesce(p_payload -> 'authors', '[]'::jsonb)) as authors(value)
    where btrim(value) <> ''
  loop
    select a.author_id into v_author_id
    from public.authors a
    where lower(a.author_name) = lower(v_author_name)
    limit 1;

    if v_author_id is null then
      insert into public.authors (author_name)
      values (v_author_name)
      on conflict (author_name) do update set author_name = excluded.author_name
      returning author_id into v_author_id;
    end if;

    insert into public.book_authors (book_id, author_id)
    values (v_book_id, v_author_id)
    on conflict do nothing;
    v_author_id := null;
  end loop;

  return v_book_id;
end;
$$;

create or replace function public.issue_book(
  p_member_identifier text,
  p_book_identifier text,
  p_loan_days integer default 14
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_member public.profiles%rowtype;
  v_book public.books%rowtype;
  v_borrowing_id bigint;
  v_caller_member_id bigint;
  v_is_staff boolean;
  v_issue_date date := current_date;
  v_due_date date;
begin
  v_is_staff := public.is_library_staff();
  v_caller_member_id := public.current_member_id();

  select p.* into v_member
  from public.profiles p
  where p.member_id = case when coalesce(p_member_identifier, '') ~ '^[0-9]+$' then p_member_identifier::bigint else -1 end
     or upper(p.member_code) = upper(coalesce(p_member_identifier, ''))
     or lower(p.email) = lower(coalesce(p_member_identifier, ''))
  limit 1
  for update;

  if not found then
    raise exception 'Member was not found.';
  end if;
  if v_member.status <> 'active' then
    raise exception 'This member account is not active.';
  end if;
  if not v_is_staff and (v_caller_member_id is null or v_caller_member_id <> v_member.member_id) then
    raise exception 'Members can only borrow books for their own account.' using errcode = '42501';
  end if;

  select b.* into v_book
  from public.books b
  where b.book_id = case when coalesce(p_book_identifier, '') ~ '^[0-9]+$' then p_book_identifier::bigint else -1 end
     or lower(b.isbn) = lower(coalesce(p_book_identifier, ''))
  limit 1
  for update;

  if not found then
    raise exception 'Book was not found.';
  end if;
  if v_book.available_copies < 1 then
    raise exception 'No copies of this book are currently available.';
  end if;
  if p_loan_days < 1 or p_loan_days > 90 then
    raise exception 'Loan period must be between 1 and 90 days.';
  end if;
  if (
    select count(*) from public.borrowings br
    where br.member_id = v_member.member_id and br.status in ('borrowed', 'overdue')
  ) >= 5 then
    raise exception 'This member has reached the active loan limit.';
  end if;

  v_due_date := v_issue_date + p_loan_days;

  insert into public.borrowings (member_id, book_id, issued_by, issue_date, due_date)
  values (v_member.member_id, v_book.book_id, case when v_is_staff then v_caller_member_id else null end, v_issue_date, v_due_date)
  returning borrowing_id into v_borrowing_id;

  update public.books
  set available_copies = available_copies - 1
  where book_id = v_book.book_id;

  return jsonb_build_object(
    'borrowing_id', v_borrowing_id,
    'member_id', v_member.member_id,
    'member_name', v_member.full_name,
    'book_id', v_book.book_id,
    'book_title', v_book.title,
    'book_isbn', v_book.isbn,
    'issue_date', v_issue_date,
    'due_date', v_due_date,
    'status', 'borrowed'
  );
end;
$$;

create or replace function public.return_book(
  p_book_identifier text,
  p_condition text default 'Good',
  p_damage_fee numeric default 0
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_loan public.borrowings%rowtype;
  v_book public.books%rowtype;
  v_member public.profiles%rowtype;
  v_return_date date := current_date;
  v_overdue_days integer;
  v_fine numeric(10, 2);
  v_fine_id bigint;
  v_reason text := '';
begin
  if not public.is_library_staff() then
    raise exception 'Only library staff can process returns.' using errcode = '42501';
  end if;

  select b.* into v_book
  from public.books b
  where b.book_id = case when coalesce(p_book_identifier, '') ~ '^[0-9]+$' then p_book_identifier::bigint else -1 end
     or lower(b.isbn) = lower(coalesce(p_book_identifier, ''))
  limit 1;

  if not found then
    raise exception 'Book was not found.';
  end if;

  select br.* into v_loan
  from public.borrowings br
  where br.book_id = v_book.book_id and br.status in ('borrowed', 'overdue')
  order by br.issue_date
  limit 1
  for update;

  if not found then
    raise exception 'No active loan exists for this book.';
  end if;

  select p.* into v_member from public.profiles p where p.member_id = v_loan.member_id;
  v_overdue_days := greatest(0, v_return_date - v_loan.due_date);
  v_fine := (v_overdue_days * 50)::numeric(10, 2) + greatest(0, coalesce(p_damage_fee, 0));

  update public.borrowings
  set return_date = v_return_date, status = 'returned'
  where borrowing_id = v_loan.borrowing_id;

  update public.books
  set available_copies = least(total_copies, available_copies + 1)
  where book_id = v_book.book_id;

  if v_overdue_days > 0 then
    v_reason := format('Overdue by %s day(s)', v_overdue_days);
  end if;
  if coalesce(p_damage_fee, 0) > 0 then
    v_reason := concat_ws('; ', nullif(v_reason, ''), format('Condition penalty (%s)', coalesce(p_condition, 'Good')));
  end if;

  if v_fine > 0 then
    insert into public.fines (borrowing_id, amount, reason, status, issued_date)
    values (v_loan.borrowing_id, v_fine, v_reason, 'unpaid', v_return_date)
    on conflict (borrowing_id) do update
      set amount = excluded.amount, reason = excluded.reason, status = 'unpaid', paid_date = null
    returning fine_id into v_fine_id;
  end if;

  return jsonb_build_object(
    'borrowing_id', v_loan.borrowing_id,
    'member_name', v_member.full_name,
    'book_title', v_book.title,
    'return_date', v_return_date,
    'overdue_days', v_overdue_days,
    'fine_amount', v_fine,
    'fine_id', v_fine_id,
    'condition', coalesce(p_condition, 'Good')
  );
end;
$$;

