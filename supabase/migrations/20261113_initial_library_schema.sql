      new.id,
      coalesce(nullif(new.raw_user_meta_data ->> 'full_name', ''), 'Library member'),
      new.email,
      coalesce(new.raw_user_meta_data ->> 'phone', '')
    )
    on conflict do nothing;
  end if;

  return new;
end;
$$;

