create or replace function public.finalize_mpesa_payment(
  p_payment_id bigint,
  p_checkout_request_id text,
  p_result_code integer,
  p_result_description text,
  p_amount numeric default null,
  p_mpesa_receipt_number text default null
)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_payment public.fine_payments%rowtype;
begin
  select * into v_payment
  from public.fine_payments
  where payment_id = p_payment_id
  for update;

  if not found then
    return false;
  end if;
  if p_checkout_request_id is null or trim(p_checkout_request_id) = '' then
    return false;
  end if;
  if v_payment.checkout_request_id is not null
    and v_payment.checkout_request_id <> p_checkout_request_id then
    return false;
  end if;
  if v_payment.checkout_request_id is null then
    update public.fine_payments
    set checkout_request_id = p_checkout_request_id, updated_at = now()
    where payment_id = p_payment_id;
  end if;
  if v_payment.status = 'paid' or (v_payment.status = 'failed' and p_result_code <> 0) then
    return true;
  end if;

  if p_result_code = 0 and (p_amount is null or p_amount <> v_payment.amount) then
    update public.fine_payments
    set status = 'failed',
        result_description = 'M-Pesa payment amount did not match the fine.',
        updated_at = now()
    where payment_id = v_payment.payment_id;
    return true;
  end if;

  if p_result_code = 0 then
    update public.fine_payments
    set status = 'paid',
        result_description = coalesce(p_result_description, ''),
        mpesa_receipt_number = p_mpesa_receipt_number,
        updated_at = now()
    where payment_id = v_payment.payment_id;

    update public.fines
    set status = 'paid', paid_date = current_date
    where fine_id = v_payment.fine_id and status = 'unpaid';
  else
    update public.fine_payments
    set status = 'failed',
        result_description = coalesce(p_result_description, ''),
        updated_at = now()
    where payment_id = v_payment.payment_id;
  end if;

  return true;
end;
$$;

