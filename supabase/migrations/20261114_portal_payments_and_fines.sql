create or replace function public.return_book(
  p_book_identifier text,
  p_condition text default 'Good',
  p_damage_fee numeric default 0,
  p_borrowing_id bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_loan public.borrowings%rowtype;
  v_book public.books%rowtype;
  v_member public.profiles%rowtype;
  v_return_date date := current_date;
  v_overdue_days integer;
  v_fine numeric(10, 2);
  v_fine_id bigint;
  v_active_loans integer;
  v_reason text := '';
begin
  if not public.is_library_staff() then
    raise exception 'Only library staff can process returns.' using errcode = '42501';
  end if;
  if coalesce(p_condition, 'Good') not in ('Good', 'Minor Wear', 'Damaged', 'Lost') then
    raise exception 'Return condition is invalid.';
  end if;
  if p_condition = 'Lost' and coalesce(p_damage_fee, 0) <= 0 then
    raise exception 'A replacement fine is required for a lost book.';
  end if;

  if p_borrowing_id is null then
    select b.* into v_book
    from public.books b
    where b.book_id = case when coalesce(p_book_identifier, '') ~ '^[0-9]+$' then p_book_identifier::bigint else -1 end
       or lower(b.isbn) = lower(coalesce(p_book_identifier, ''))
    limit 1;

    if not found then
      raise exception 'Book was not found.';
    end if;

    select count(*) into v_active_loans
    from public.borrowings br
    where br.book_id = v_book.book_id and br.status in ('borrowed', 'overdue');
    if v_active_loans > 1 then
      raise exception 'More than one copy of this book is on loan. Select the specific loan from the active-loans list.';
    end if;

    select br.* into v_loan
    from public.borrowings br
    where br.book_id = v_book.book_id and br.status in ('borrowed', 'overdue')
    order by br.issue_date, br.borrowing_id
    limit 1
    for update;
    if not found then
      raise exception 'No active loan exists for this book.';
    end if;
  else
    select br.* into v_loan
    from public.borrowings br
    where br.borrowing_id = p_borrowing_id and br.status in ('borrowed', 'overdue')
    for update;

    if not found then
      raise exception 'No active loan exists for this book.';
    end if;

    select b.* into v_book from public.books b where b.book_id = v_loan.book_id;
  end if;

  select p.* into v_member from public.profiles p where p.member_id = v_loan.member_id;
  v_overdue_days := greatest(0, v_return_date - v_loan.due_date);
  v_fine := (v_overdue_days * 50)::numeric(10, 2) + greatest(0, coalesce(p_damage_fee, 0));

  update public.borrowings
  set return_date = v_return_date, status = 'returned'
  where borrowing_id = v_loan.borrowing_id;

  if p_condition = 'Lost' then
    update public.books
    set total_copies = greatest(available_copies, total_copies - 1)
    where book_id = v_book.book_id;
  else
    update public.books
    set available_copies = least(total_copies, available_copies + 1)
    where book_id = v_book.book_id;
  end if;

  if v_overdue_days > 0 then
    v_reason := format('Overdue by %s day(s)', v_overdue_days);
  end if;
  if coalesce(p_damage_fee, 0) > 0 then
    v_reason := concat_ws('; ', nullif(v_reason, ''), format('Condition/replacement penalty (%s)', coalesce(p_condition, 'Good')));
  end if;

  if v_fine > 0 then
    insert into public.fines (borrowing_id, member_id, amount, reason, status, issued_date)
    values (v_loan.borrowing_id, v_loan.member_id, v_fine, v_reason, 'unpaid', v_return_date)
    returning fine_id into v_fine_id;
  end if;

  return jsonb_build_object(
    'borrowing_id', v_loan.borrowing_id,
    'member_name', v_member.full_name,
    'book_title', v_book.title,
    'return_date', v_return_date,
    'overdue_days', v_overdue_days,
    'fine_amount', v_fine,
    'fine_id', v_fine_id,
    'condition', coalesce(p_condition, 'Good')
  );
end;
$$;

