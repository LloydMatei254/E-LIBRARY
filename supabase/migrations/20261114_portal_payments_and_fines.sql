create or replace function public.update_member_details(
  p_member_id bigint,
  p_full_name text,
  p_phone text
)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if not public.is_library_staff() then
    raise exception 'Only library staff can update member profiles.' using errcode = '42501';
  end if;
  if length(trim(coalesce(p_full_name, ''))) = 0 then
    raise exception 'Member name is required.';
  end if;
  if not exists (
    select 1 from public.profiles
    where member_id = p_member_id and role = 'member'
  ) then
    raise exception 'Member was not found.';
  end if;

  update public.profiles
  set full_name = trim(p_full_name), phone = trim(coalesce(p_phone, ''))
  where member_id = p_member_id;
  return true;
end;
$$;

create or replace function public.add_member_fine(
  p_member_id bigint,
  p_amount numeric,
  p_reason text
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_fine_id bigint;
begin
  if not public.is_library_staff() then
    raise exception 'Only library staff can add a fine.' using errcode = '42501';
  end if;
  if p_amount is null or p_amount <= 0 then
    raise exception 'Fine amount must be greater than zero.';
  end if;
  if not exists (
    select 1 from public.profiles
    where member_id = p_member_id and role = 'member'
  ) then
    raise exception 'Member was not found.';
  end if;

  insert into public.fines (member_id, borrowing_id, amount, reason, status, issued_date)
  values (p_member_id, null, p_amount, coalesce(nullif(trim(p_reason), ''), 'Library fine'), 'unpaid', current_date)
  returning fine_id into v_fine_id;
  return v_fine_id;
end;
$$;

